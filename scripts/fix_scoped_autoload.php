<?php

declare(strict_types=1);

if ($argc < 2) {
    fwrite(STDERR, "Usage: php fix_scoped_autoload.php <dist-dir>\n");
    exit(1);
}

$distDir = rtrim($argv[1], '/');
$composerDir = $distDir . '/vendor/composer';

$autoloadReal = $composerDir . '/autoload_real.php';
$autoloadPsr4 = $composerDir . '/autoload_psr4.php';
$autoloadStatic = $composerDir . '/autoload_static.php';

foreach ([$autoloadReal, $autoloadPsr4, $autoloadStatic] as $file) {
    if (!file_exists($file)) {
        fwrite(STDERR, "Missing required file: {$file}\n");
        exit(1);
    }
}

function prefix_vendor_namespace(string $namespace): string
{
    if (str_starts_with($namespace, 'Civi\\Wallet\\') || str_starts_with($namespace, 'CRM_')) {
        return $namespace;
    }

    return 'Civi\\Wallet\\Vendor\\' . $namespace;
}

function export_php(mixed $value): string
{
    return var_export($value, true);
}

function normalize_path_for_runtime(string $path, string $distDir): string
{
    $distDir = rtrim(str_replace('\\', '/', $distDir), '/');
    $path = str_replace('\\', '/', $path);

    if (str_starts_with($path, $distDir . '/vendor/')) {
        return '$vendorDir . ' . var_export(substr($path, strlen($distDir . '/vendor')), true);
    }

    if (str_starts_with($path, $distDir . '/')) {
        return '$baseDir . ' . var_export(substr($path, strlen($distDir)), true);
    }

    return var_export($path, true);
}

function export_php_pathaware(mixed $value, string $distDir, int $indent = 0): string
{
    if (is_array($value)) {
        if ($value === []) {
            return 'array (
' . str_repeat(' ', $indent) . ')';
        }

        $padding = str_repeat(' ', $indent);
        $childPadding = str_repeat(' ', $indent + 2);
        $lines = ["array ("];

        foreach ($value as $key => $item) {
            $lines[] = $childPadding . export_php($key) . ' => ' . export_php_pathaware($item, $distDir, $indent + 2) . ',';
        }

        $lines[] = $padding . ')';
        return implode("\n", $lines);
    }

    if (is_string($value)) {
        return normalize_path_for_runtime($value, $distDir);
    }

    return export_php($value);
}

$autoloadRealContent = file_get_contents($autoloadReal);
$autoloadRealContent = str_replace(
    "'Composer\\Autoload\\ClassLoader' === \$class",
    "'Civi\\Wallet\\Vendor\\Composer\\Autoload\\ClassLoader' === \$class",
    $autoloadRealContent
);
$autoloadRealContent = str_replace(
    "array('ComposerAutoloaderInit",
    "array('Civi\\Wallet\\Vendor\\ComposerAutoloaderInit",
    $autoloadRealContent
);
file_put_contents($autoloadReal, $autoloadRealContent);

$psr4Map = require $autoloadPsr4;
$fixedPsr4Map = [];
foreach ($psr4Map as $namespace => $paths) {
    $fixedPsr4Map[prefix_vendor_namespace($namespace)] = $paths;
}

$autoloadPsr4Code = <<<PHP
<?php

namespace Civi\\Wallet\\Vendor;

// autoload_psr4.php @generated by Composer
\$vendorDir = \\dirname(__DIR__);
\$baseDir = \\dirname(\$vendorDir);

return %s;
PHP;

file_put_contents($autoloadPsr4, sprintf($autoloadPsr4Code, export_php_pathaware($fixedPsr4Map, $distDir) . ';'));

$autoloadStaticContent = file_get_contents($autoloadStatic);
if (!preg_match('/class\s+([A-Za-z0-9_]+)/', $autoloadStaticContent, $matches)) {
    fwrite(STDERR, "Unable to detect Composer static autoload class.\n");
    exit(1);
}

require_once $autoloadStatic;

$autoloadStaticClass = null;
foreach ([
    'Civi\\Wallet\\Vendor\\Composer\\Autoload\\' . $matches[1],
    'Composer\\Autoload\\' . $matches[1],
] as $candidateClass) {
    if (class_exists($candidateClass, false)) {
        $autoloadStaticClass = $candidateClass;
        break;
    }
}

if (!$autoloadStaticClass) {
    fwrite(STDERR, "Unable to load Composer static autoload class.\n");
    exit(1);
}

$prefixLengthsPsr4 = $autoloadStaticClass::$prefixLengthsPsr4;
$prefixDirsPsr4 = $autoloadStaticClass::$prefixDirsPsr4;
$prefixesPsr0 = $autoloadStaticClass::$prefixesPsr0;
$classMap = $autoloadStaticClass::$classMap;
$files = $autoloadStaticClass::$files ?? [];

$fixedPrefixLengthsPsr4 = [];
foreach ($prefixLengthsPsr4 as $firstLetter => $namespaces) {
    foreach ($namespaces as $namespace => $length) {
        $fixedNamespace = prefix_vendor_namespace($namespace);
        $fixedPrefixLengthsPsr4[$fixedNamespace[0]][$fixedNamespace] = strlen($fixedNamespace);
    }
}

$fixedPrefixDirsPsr4 = [];
foreach ($prefixDirsPsr4 as $namespace => $dirs) {
    $fixedPrefixDirsPsr4[prefix_vendor_namespace($namespace)] = $dirs;
}

$autoloadStaticCode = <<<PHP
<?php

// autoload_static.php @generated by Composer
namespace Civi\\Wallet\\Vendor\\Composer\\Autoload;

class %s
{
    public static \$files = array (
    );
    public static \$prefixLengthsPsr4 = %s;
    public static \$prefixDirsPsr4 = array (
    );
    public static \$prefixesPsr0 = array (
    );
    public static \$classMap = array (
    );

    public static function getInitializer(ClassLoader \$loader)
    {
        return \\Closure::bind(function () use (\$loader) {
            \$vendorDir = \\dirname(__DIR__);
            \$baseDir = \\dirname(\$vendorDir);
            %s::\$files = %s;
            %s::\$prefixDirsPsr4 = %s;
            %s::\$prefixesPsr0 = %s;
            %s::\$classMap = %s;
            \$loader->prefixLengthsPsr4 = %s::\$prefixLengthsPsr4;
            \$loader->prefixDirsPsr4 = %s::\$prefixDirsPsr4;
            \$loader->prefixesPsr0 = %s::\$prefixesPsr0;
            \$loader->classMap = %s::\$classMap;
        }, null, ClassLoader::class);
    }
}
PHP;

file_put_contents(
    $autoloadStatic,
    sprintf(
        $autoloadStaticCode,
        $matches[1],
        export_php($fixedPrefixLengthsPsr4),
        $matches[1],
        export_php_pathaware($files, $distDir),
        $matches[1],
        export_php_pathaware($fixedPrefixDirsPsr4, $distDir),
        $matches[1],
        export_php_pathaware($prefixesPsr0, $distDir),
        $matches[1],
        export_php_pathaware($classMap, $distDir),
        $matches[1],
        $matches[1],
        $matches[1],
        $matches[1],
    )
);

echo "Scoped Composer autoload files fixed in {$distDir}\n";
